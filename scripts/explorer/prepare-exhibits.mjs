import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import {readFile,writeFile,stat} from 'node:fs/promises';
const [toolchain,source]=process.argv.slice(2);
if(!toolchain||!source)throw new Error('Usage: node prepare-exhibits.mjs TOOLCHAIN RAW_DIRECTORY');
const require=createRequire(path.resolve(toolchain,'package.json'));
const {NodeIO}=await import(pathToFileURL(require.resolve('@gltf-transform/core')));
const {ALL_EXTENSIONS}=await import(pathToFileURL(require.resolve('@gltf-transform/extensions')));
const {dedup,prune,meshopt,simplify}=await import(pathToFileURL(require.resolve('@gltf-transform/functions')));
const {MeshoptEncoder,MeshoptDecoder,MeshoptSimplifier}=await import(pathToFileURL(require.resolve('meshoptimizer')));
await Promise.all([MeshoptEncoder.ready,MeshoptDecoder.ready,MeshoptSimplifier.ready]);
const io=new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({'meshopt.encoder':MeshoptEncoder,'meshopt.decoder':MeshoptDecoder});
const doc=await io.read(path.resolve(source,'exhibits.glb'));
await doc.transform(dedup(),simplify({simplifier:MeshoptSimplifier,ratio:.55,error:.0002,lockBorder:true}),prune(),meshopt({encoder:MeshoptEncoder,level:'high'}));
const folder='public/habitat/explorer/v1';await io.write(folder+'/exhibits.glb',doc);
const manifest=JSON.parse(await readFile(folder+'/manifest.json','utf8'));
manifest.assets=manifest.assets.filter(asset=>!['environment.glb','exhibits.glb'].includes(asset.file));
manifest.assets.push({file:'exhibits.glb',bytes:(await stat(folder+'/exhibits.glb')).size,triangles:doc.getRoot().listMeshes().reduce((n,m)=>n+m.listPrimitives().reduce((sum,p)=>sum+(p.getIndices()?.getCount()??p.getAttribute('POSITION').getCount())/3,0),0)});
await writeFile(folder+'/manifest.json',JSON.stringify(manifest,null,2)+'\n');
console.log(manifest.assets.at(-1));
